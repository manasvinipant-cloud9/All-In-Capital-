// Generates seed/ — ALL FICTIONAL (CAPilot deck text comes from the shared Drive). Deterministic via fixed seed.
import PDFDocument from "pdfkit";
import { createWriteStream, mkdirSync, writeFileSync } from "node:fs";
import { APPS } from "./apps.ts";
import { PORTFOLIO, MEMOS, MEETINGS } from "./content.ts";

let s = 42; const rnd = () => (s = (s * 1664525 + 1013904223) % 4294967296) / 4294967296;
const pick = <T,>(a: T[]) => a[Math.floor(rnd() * a.length)];
const csv = (rows: Record<string, any>[]) => { const h = Object.keys(rows[0]); const q = (v: any) => `"${String(v).replace(/"/g, '""')}"`; return [h.join(","), ...rows.map(r => h.map(k => q(r[k])).join(","))].join("\n"); };
for (const d of ["seed/forms", "seed/decks", "seed/memos", "seed/meetings", "seed/exports"]) mkdirSync(d, { recursive: true });

for (const a of APPS) {
  writeFileSync(`seed/forms/${a.slug}.json`, JSON.stringify({ synthetic: a.slug !== "capilot", ...a.form }, null, 2));
  const doc = new PDFDocument({ autoFirstPage: false });
  doc.pipe(createWriteStream(`seed/decks/${a.slug}.pdf`));
  a.deck.forEach((t, i) => { doc.addPage(); doc.fontSize(20).text(`${a.company} (page ${i + 1})`).moveDown().fontSize(14).text(t); });
  doc.end();
}
writeFileSync("seed/traps.json", JSON.stringify(APPS.map(a => ({ slug: a.slug, trap: a.trap })), null, 2));
writeFileSync("seed/portfolio.json", JSON.stringify(PORTFOLIO, null, 2));
MEMOS.forEach((x, i) => writeFileSync(`seed/memos/${String(i + 1).padStart(2, "0")}-${x.company.replace(/\W+/g, "-").toLowerCase()}.md`,
  `# ${x.company}\n_Fictional memo._\n\n## What it does\n${x.what}\n\n## Founder assessment\n${x.founder}\n\n## Risks and open questions\n${x.risks}\n\n## Why we ${x.outcome === "invested" ? "invested" : "passed"}\n${x.why}\n`));
MEETINGS.forEach(x => writeFileSync(`seed/meetings/meeting-${x.n}.md`, `# ${x.title}\n\n${x.notes}\n`));

// Loop 1: 40 rows, 12 overturned
const sectors = ["Fintech", "Deeptech", "Consumer tech", "Consumer brand", "B2B SaaS"], ftypes = ["first-time", "repeat", "domain-expert"];
const cities = ["Bengaluru", "Mumbai", "Pune", "Delhi", "Ahmedabad", "Jaipur"];
const reasons = ["Owns the credit risk, thesis fits", "Pedigree overrated; no repeat data", "Regulatory bet, outside thesis", "Founder did field work first", "Structure does not fit a pre-seed cheque", "Revenue path nearer than the score implies"];
const over = new Set<number>(); while (over.size < 12) over.add(Math.floor(rnd() * 40));
const loop1 = Array.from({ length: 40 }, (_, i) => {
  const score = Math.round((3 + rnd() * 6) * 10) / 10, call = score >= 6.5 ? "go" : "no-go";
  const final = over.has(i) ? (call === "go" ? "no-go" : "go") : call;
  return { row_id: `L1-${i + 1}`, date: `2026-0${1 + Math.floor(i / 8)}-${String(10 + (i % 15)).padStart(2, "0")}`, startup: `SynthCo ${i + 1}`, founder_type: pick(ftypes), sector: pick(sectors), stage: pick(["Pre-seed", "Seed"]), city: pick(cities),
    application_summary: "Synthetic application summary.", system_score: score, system_call: call, riya_final_call: final, riya_reason: over.has(i) ? pick(reasons) : "", synthetic: true };
});
writeFileSync("seed/exports/loop1_screening.csv", csv(loop1));

// Loop 2: 60 rows; ~58% rewritten; Riya's emails 42-61 words; 2 dirty rows
const nums = ["38 retailers", "46% month-3 repeat", "1,900 loans", "40 paying teams", "INR 9 L monthly revenue", "120 store visits"];
const slotsTxt = ["Tuesday 2 Dec 3pm IST", "Thursday 4 Dec 4pm IST"];
const words = (t: string) => t.trim().split(/\s+/).length;
const loop2 = Array.from({ length: 60 }, (_, i) => {
  const n = pick(nums), fn = pick(["Asha", "Ravi", "Meera", "Kabir", "Sana", "Nikhil"]);
  const draft = `Hi ${fn},\n\nImpressive technology! We love what you are building and were excited to see your traction of ${n} and a very large market. Would you be open to a chat sometime to tell us more about the business?\n\nBest regards,\nRiya`;
  let final = draft;
  if (i === 58) final = `Dear Ms ${fn}, ${"We are pleased to receive your application and would like to introduce our fund in detail. ".repeat(8)}Kind regards`;
  else if (i === 59) final = Array(136).fill("boilerplate").join(" ");
  else if (rnd() < 0.58) final = `Hi ${fn},\n${n} is unusual for a pre-seed team in this sector. How did you get there with so little spend?\nWould ${slotsTxt[0]} or ${slotsTxt[1]} work for a 30-minute call?\nRiya\nAll In Capital`;
  return { row_id: `L2-${i + 1}`, date_sent: `2026-0${1 + Math.floor(i / 12)}-${String(5 + (i % 20)).padStart(2, "0")}`, founder_name: fn, startup: `SynthCo ${i + 1}`, founder_type: pick(ftypes), sector: pick(sectors), stage: "Pre-seed", city: pick(cities),
    founder_background: "Synthetic background", traction_facts: n, system_draft: draft, riya_final_email: final, synthetic: true, riya_words: words(final) };
});
writeFileSync("seed/exports/loop2_first_email.csv", csv(loop2));
writeFileSync("seed/README.md", "# Seed data\nAll fictional and generated by `pnpm seed:gen`, except `decks/capilot.pdf` and `forms/capilot.json`, which are based on the CAPilot deck in the shared Drive. Only that one file was readable from the Drive folders in the build session; the rest are generated per the master prompt.\n");
console.log("seed written");
